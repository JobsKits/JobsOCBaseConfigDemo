static NSString *JobsCollectionLanguage(NSString *language) {
    const char *code = language.lowercaseString.UTF8String;
    if (!code) {
        return @"en";
    }
    if (strncmp(code, "zh", 2) == 0) {
        BOOL traditional = strstr(code, "hant") || strstr(code, "-tw") || strstr(code, "-hk") || strstr(code, "-mo") || strstr(code, "_tw") || strstr(code, "_hk") || strstr(code, "_mo");
        return traditional ? @"zh-Hant" : @"zh-Hans";
    }
    for (NSString *candidate in @[@"bo", @"en", @"ja", @"fr", @"es", @"de", @"ru", @"ko"]) {
        const char *prefix = candidate.UTF8String;
        if (strncmp(code, prefix, 2) == 0 && (code[2] == '\0' || code[2] == '-' || code[2] == '_')) {
            return candidate;
        }
    }
    return @"en";
}

@implementation JobsDeviceCollectionText

+(NSArray<NSString *> *)languageCodes {
    return @[@"zh-Hans", @"zh-Hant", @"bo", @"en", @"ja", @"fr", @"es", @"de", @"ru", @"ko"];
}

+(NSString *)text:(NSString *)key
        language:(NSString *)language {
    NSString *code = JobsCollectionLanguage(language);
    NSString *value = JobsCollectionTranslations()[code][key];
    NSCAssert(value != nil, @"Missing device collection translation: %@ / %@", code, key);
    return value ?: key;
}

